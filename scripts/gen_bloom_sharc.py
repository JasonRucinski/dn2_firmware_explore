"""Package Bloom's SHARC objects for `dnfw.bloom.dsp` (milestones B3a and B3b).

    python scripts/gen_bloom_sharc.py [--assemble]

`dnfw.bloom.dsp` applies committed objects, never an assembler, so the mod runs
anywhere. This writes `src/dnfw/bloom/sharc_code.json` from:

- `csrc/bloom/sharc/bloom_loop.asm`, the type-7 render loop (at sw 0x16eb00), and
  the entry `JUMP 0x16eb00;` (written at sw 0x1c9448), one instruction;
- `csrc/bloom/sharc/pulse.asm`, PULSE on FREQ (B3b, at sw 0x16f400), and its
  `JUMP 0x16f400;` (written at sw 0x1c9fb9, before the call of the unpack),

each assembled with selache's `selas` and the post-fixes in
`scripts/sharc_waverider_m3.py` when `--assemble`. Without it, the committed objects
are kept, and a source that no longer matches its object (sha256, LF-normalised) is
refused. selache (GPL-3.0) is a tool here; nothing of it is copied.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from dnfw.bloom import dsp  # noqa: E402

SHARC = ROOT / "csrc" / "bloom" / "sharc"
SRC = SHARC / "bloom_loop.asm"
PULSE_SRC = SHARC / "pulse.asm"
TOOLCHAIN = "selache selas -proc ADSP-21569 (js216/selache 2b26d3b, GPL-3.0)"
ENTRY_LINE = f"JUMP {dsp.LOOP_SW:#x};"
PULSE_LINE = f"JUMP {dsp.PULSE_SW:#x};"


def sha(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--assemble", action="store_true")
    a = ap.parse_args(argv)
    if not a.assemble:
        spec = json.loads(dsp.CODE.read_text(encoding="utf-8"))
        for key, src in (("loop", SRC), ("pulse", PULSE_SRC)):
            if spec[key]["source_sha256"] != sha(src):
                raise SystemExit(f"{dsp.CODE.name} is stale for {src.name}: rerun with --assemble")
        print(f"{dsp.CODE.relative_to(ROOT)} is current")
        return 0
    import sharc_waverider_m3 as m3  # noqa: PLC0415  (needs selas only when assembling)
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        be, offsets = m3._selas(SRC, work)
        jump, _ = m3._selas_line(ENTRY_LINE, work)
        pbe, poffsets = m3._selas(PULSE_SRC, work)
        pjump, _ = m3._selas_line(PULSE_LINE, work)
    spec = {"note": "generated by scripts/gen_bloom_sharc.py; do not edit",
            "loop": {"source": SRC.relative_to(ROOT).as_posix(), "source_sha256": sha(SRC),
                     "toolchain": TOOLCHAIN, "section": "seg_pmco", "load_sw": hex(dsp.LOOP_SW),
                     "object_parcels_be": be.hex(), "instruction_offsets": offsets},
            "entry_jump": {"source": ENTRY_LINE, "toolchain": TOOLCHAIN, "at_sw": hex(dsp.ENTRY_SW),
                           "object_parcels_be": jump.hex()},
            "pulse": {"source": PULSE_SRC.relative_to(ROOT).as_posix(), "source_sha256": sha(PULSE_SRC),
                      "toolchain": TOOLCHAIN, "section": "seg_pmco", "load_sw": hex(dsp.PULSE_SW),
                      "object_parcels_be": pbe.hex(), "instruction_offsets": poffsets},
            "pulse_jump": {"source": PULSE_LINE, "toolchain": TOOLCHAIN, "at_sw": hex(dsp.CALL_SITE_SW),
                           "object_parcels_be": pjump.hex()}}
    dsp.CODE.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {dsp.CODE.relative_to(ROOT)}: loop {len(be)} B ({len(offsets)} instructions), "
          f"entry {len(jump)} B; pulse {len(pbe)} B ({len(poffsets)} instructions), jump {len(pjump)} B")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
